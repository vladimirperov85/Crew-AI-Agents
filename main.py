from crewai import LLM, Agent, Crew, Process, Task

# 1. Настраиваем модель — подключаемся к локальной Ollama
llm = LLM(
    model="ollama/qwen2.5-coder:7b",
    base_url="http://localhost:11434",
)

# yandex_llm = LLM(
#     model="ollama/yandex/YandexGPT-5-Lite-8B-instruct-GGUF:latest",
#     base_url="http://localhost:11434",
# )


# Агент 1: аналитик
analyst = Agent(
    role="Технический аналитик",
    goal="Анализировать технологии и выделять ключевые преимущества и риски",
    backstory=(
        "Ты — технический аналитик с опытом в AI и машинном обучении. "
        "Ты умеешь структурированно анализировать технологии: "
        "выделять преимущества, недостатки, риски и области применения. "
        "Твои анализы краткие, но содержательные."
    ),
    llm=llm,
    max_iterations=5,
)

# Агент 2: писатель
writer = Agent(
    role="Технический писатель",
    goal="Превращать технические анализы в понятные отчёты для разработчиков",
    backstory=(
        "Ты — технический писатель. Ты умеешь брать сырой анализ и превращать его "
        "в чёткий, структурированный отчёт. Ты пишешь простым языком, "
        "сохраняя техническую точность."
    ),
    llm=llm,
    max_iterations=5,
)

# Агент 3: редактор
editor = Agent(
    role="Технический редактор",
    goal="Проверять тексты на точность, структуру и соответствие формату",
    backstory=(
        "Ты — технический редактор. Ты проверяешь тексты на точность фактов, "
        "структуру, стиль и соответствие заданному формату. "
        "Ты даёшь конкретные рекомендации по улучшению."
    ),
    llm=llm,
    max_iterations=5,
)


# Задача 1: анализ
analysis_task = Task(
    description=(
        "Проанализируй тему: «Преимущества и недостатки использования локальных LLM-моделей "
        "(например, через Ollama) вместо облачных API (OpenAI, Anthropic)». "
        "Выдели 3-4 преимущества и 2-3 недостатка."
    ),
    expected_output="Структурированный список: 3-4 преимущества и 2-3 недостатка локальных LLM.",
    agent=analyst,
)


# Задача 2: отчёт на основе анализа
report_task = Task(
    description=(
        "Напиши краткий отчёт (5-6 предложений) о локальных LLM для разработчиков. "
        "Используй следующий анализ как основу:"
    ),
    expected_output="Отчёт из 5-6 предложений: введение, преимущества, недостатки, вывод.",
    agent=writer,
    context=[analysis_task],  # <-- результат задачи 1 подставляется сюда
)

# Задача 3: проверка качества
review_task = Task(
    description="Проверь отчёт на соответствие формату (5-6 предложений) и точность фактов. Дай оценку и рекомендации.",
    expected_output="Оценка отчёта: формат (да/нет), точность фактов, конкретные рекомендации по улучшению.",
    agent=editor,
    context=[report_task],
)


# 4. Собираем команду и запускаем
crew = Crew(
    agents=[analyst, writer, editor],  # список агентов
    tasks=[analysis_task, report_task, review_task],  # список задач
    process=Process.sequential,       # последовательный процесс
    verbose=True,  # показывать подробности выполнения
)

# 5. Запускаем
result = crew.kickoff()
print(result)
